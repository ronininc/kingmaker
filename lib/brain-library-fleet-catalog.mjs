// lib/brain-library-fleet-catalog.mjs — Fleet Replication follow-on 1:
// publication of portion pin manifests in the shipped Brain Library catalog.
//
// v1 built buildPortionManifest() (lib/brain-library-fleet.mjs) but the shipped
// door catalog carried only whole-item pins, so a client had to build every
// manifest itself from bytes it already held — which defeats the point: the
// manifest is what lets a client accept portions from a peer it does not
// trust, before it holds anything. This module is the catalog side of that
// contract:
//
//   buildFleetCatalog({ sources })  — one pass over each catalog source,
//     computing portionBytes + portionSha256[] (and the whole-item pin for
//     virtual sources that carry none), producing the fleet catalog document.
//   writeFleetCatalog / loadFleetCatalog — the published file's write/read
//     path. The loader VALIDATES every entry: an entry whose portion manifest
//     is missing or the wrong length is reported in `rejected` with its
//     reason and never handed to a fetcher, mirroring the fetcher's own
//     FLEET_PIN_MANIFEST_MISSING refusal.
//
// The catalog file lives at catalog/fleet.json in the tree — the same channel
// that carries the whole-item pins today (catalog/methods/index.json,
// catalog/tools/index.json, library.json). It is regenerated by
// scripts/build-fleet-catalog.mjs from buildCatalogSources(), i.e. from the
// same production source construction the access layer serves from.
//
// A model whose weights arrive through an injected range fetcher is just a
// source to this builder: pass buildCatalogSources({ fetchModelRange, models })
// and its descriptor lands in the same file, pins computed from the door's own
// range reads at publish time.

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { DEFAULT_FLEET_PORTION_BYTES, portionCount } from './brain-library-fleet.mjs';

export const FLEET_CATALOG_SCHEMA = 'kingmaker.fleet-catalog/1';

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

function catalogError(code, message, extra = {}) {
  const err = new Error(`brain-library-fleet-catalog: ${message}`);
  err.code = code;
  return Object.assign(err, extra);
}

/**
 * One descriptor, built in a single pass over the source's bytes: every
 * portion is read once, its pin recorded, and the whole-item hash accumulated
 * in the same pass. When the source already carries a whole-item pin it is
 * checked against the computed hash — a catalog builder must never publish a
 * whole pin its own bytes do not satisfy.
 */
export async function buildFleetDescriptor(source, { portionBytes = DEFAULT_FLEET_PORTION_BYTES } = {}) {
  const count = portionCount(source.size, portionBytes);
  const whole = createHash('sha256');
  const portionSha256 = [];
  for (let i = 0; i < count; i++) {
    const start = i * portionBytes;
    const length = Math.min(portionBytes, source.size - start);
    const data = await source.readRange(start, length);
    if (data.length !== length) {
      throw catalogError('FLEET_CATALOG_SHORT_READ', `"${source.id}" served ${data.length} of ${length} bytes for portion ${i} — refusing to publish a manifest over short bytes`, { id: source.id, portion: i });
    }
    whole.update(data);
    portionSha256.push(sha256(data));
  }
  const computed = whole.digest('hex');
  if (source.sha256 && source.sha256 !== computed) {
    throw catalogError('FLEET_CATALOG_PIN_CONFLICT', `"${source.id}" carries whole pin ${source.sha256} but its bytes hash to ${computed} — refusing to publish`, { id: source.id });
  }
  return {
    id: source.id, kind: source.kind, name: source.name ?? source.id,
    size: source.size, sha256: computed, portionBytes, portionSha256,
  };
}

/** Item kinds the fleet catalog publishes. Training *parts* are members of
 *  their module item, not items of their own, so `training-part:*` sources
 *  are not listed. */
export const FLEET_CATALOG_KINDS = new Set(['method', 'training', 'knowledge', 'tool', 'model']);

/**
 * Build the fleet catalog document from a sources map (the shape
 * buildCatalogSources returns). Sources outside FLEET_CATALOG_KINDS are
 * skipped and named in `skipped`, never silently dropped.
 */
export async function buildFleetCatalog({ sources, portionBytes = DEFAULT_FLEET_PORTION_BYTES, generatedAt = new Date().toISOString() } = {}) {
  const byId = sources instanceof Map ? sources : new Map(Object.entries(sources ?? {}));
  const items = [];
  const skipped = [];
  for (const source of byId.values()) {
    if (!FLEET_CATALOG_KINDS.has(source.kind)) { skipped.push({ id: source.id, kind: source.kind, reason: 'kind not published as a fleet item' }); continue; }
    items.push(await buildFleetDescriptor(source, { portionBytes }));
  }
  items.sort((a, b) => a.id.localeCompare(b.id));
  return { schema: FLEET_CATALOG_SCHEMA, generatedAt, portionBytes, items, skipped };
}

/** The problems with one descriptor, [] when it is complete and consistent. */
export function fleetDescriptorProblems(d) {
  const problems = [];
  if (!d?.id) problems.push('no id');
  if (!Number.isFinite(d?.size) || d.size < 0) problems.push('no valid size');
  if (!d?.sha256) problems.push('no whole-item sha256 pin');
  if (problems.length) return problems;
  let count;
  try { count = portionCount(d.size, d.portionBytes ?? DEFAULT_FLEET_PORTION_BYTES); }
  catch (e) { return [...problems, String(e?.message ?? e)]; }
  if (!Array.isArray(d.portionSha256)) problems.push('portionSha256 missing — no portion pin manifest');
  else if (d.portionSha256.length !== count) problems.push(`portionSha256 has ${d.portionSha256.length} pins, ${count} portions expected`);
  else if (d.portionSha256.some((p) => !/^[0-9a-f]{64}$/.test(p))) problems.push('a portion pin is not a sha256 hex digest');
  return problems;
}

/**
 * Read and validate a published fleet catalog. Returns { catalog, items,
 * rejected }: `items` is a Map of id → descriptor holding ONLY entries that
 * pass fleetDescriptorProblems; every refused entry is named in `rejected`
 * with its problems. A wrong-schema or unparseable file throws — a client
 * must never quietly fall back to trusting unpinned portions.
 */
export async function loadFleetCatalog(path) {
  const catalog = JSON.parse(await readFile(path, 'utf8'));
  if (catalog?.schema !== FLEET_CATALOG_SCHEMA || !Array.isArray(catalog?.items)) {
    throw catalogError('FLEET_CATALOG_SCHEMA', `${path} is not a ${FLEET_CATALOG_SCHEMA} document`);
  }
  const items = new Map();
  const rejected = [];
  for (const d of catalog.items) {
    const problems = fleetDescriptorProblems(d);
    if (problems.length) { rejected.push({ id: d?.id ?? null, problems }); continue; }
    if (items.has(d.id)) { rejected.push({ id: d.id, problems: ['duplicate id in catalog'] }); continue; }
    items.set(d.id, d);
  }
  return { catalog, items, rejected };
}

/** Write a built catalog document to its published path. */
export async function writeFleetCatalog(path, catalog) {
  await writeFile(path, `${JSON.stringify(catalog, null, 1)}\n`, { mode: 0o644 });
  return path;
}

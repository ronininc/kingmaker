// lib/armor-bundle-build.mjs — THE BAKE SIDE of the sealed armor bundle (Kingmaker code).
//
// scripts/build-payload.mjs stages the payload from this source tree, then calls sealArmorPart()
// to transform the staged scripture-armor/ part before the manifest is written:
//
//   BEFORE (the 4.4.0 shape): 142 files of readable Scripture Armor — the whole paid service's
//   source (armor.mjs, vaultd.mjs, cell.mjs, airlock.mjs, the test batteries, the harness with
//   TWO more nested copies of the tree, every report) — inside the free Kingmaker download.
//
//   AFTER: five files. armor-bundle.scripture (the runtime armor modules — armor.mjs + scan.mjs
//   + refit-net.mjs, the only armor code any Kingmaker runtime path loads — merged into one
//   module and sealed with Scripture Armor itself), armor-bundle.key.scripture (the bundle
//   recipient's identity, sealed to a per-bake escrow identity: the loader's bootstrap), and
//   three generated loader shims at the original module paths, so every existing import in
//   lib/ and light-runtime/ resolves exactly as before — to lib/armor-bundle.mjs, which unseals
//   and evaluates the bundle in memory. The rest of the armor tree does not ship at all: the
//   daemon, the cell, the airlock and the test/harness trees are the armor estate's own
//   deployment, never a Kingmaker payload concern.
//
// Per-bake identities (bundle signer, bundle recipient, escrow) are minted fresh in a scratch
// dir on every bake and never leave it — only the two sealed packages, the shims, and the
// generated lib/armor-bundle-pin.mjs (signer fingerprint pin + escrow identity) enter the
// payload. Robbie's ruling, 2026-10-28 16:54 MST: "people looking at Kingmaker code can't take
// my paid service free."
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { BUNDLE_FILE, ESCROW_FILE } from './armor-bundle.mjs';

export const ARMOR_BUNDLE_KEEP = Object.freeze([BUNDLE_FILE, ESCROW_FILE, 'armor.mjs', 'refit-net.mjs', 'scan.mjs']);
const SHIM_NOTE = '// GENERATED BY THE KINGMAKER BAKE (lib/armor-bundle-build.mjs) — this is a loader shim, not Scripture Armor source.\n'
  + '// The real module ships sealed in armor-bundle.scripture and is unsealed + evaluated in memory by\n'
  + '// lib/armor-bundle.mjs. If the bundle cannot be opened, every export below throws its coded refusal.\n';

// ── Source analysis helpers (textual, fail-loud: any shape drift stops the bake) ────────────

const IMPORT_RE = /import\s+(?:[\s\S]*?\s+from\s+)?['"]([^'"]+)['"];?/g;

function parseImports(src, fileLabel) {
  const imports = [];
  for (const m of src.matchAll(IMPORT_RE)) {
    const stmt = m[0];
    const specifier = m[1];
    const locals = [];
    const body = stmt.replace(/^import\s+/, '').replace(/\s+from\s+['"][^'"]+['"];?$/, '').replace(/;$/, '').trim();
    if (body && !body.startsWith("'") && !body.startsWith('"')) {
      const named = /\{([\s\S]*)\}/.exec(body)?.[1];
      const rest = body.replace(/\{[\s\S]*\}/, '').replace(/,$/, '').trim();
      if (rest) {
        const ns = /\*\s+as\s+([A-Za-z_$][\w$]*)/.exec(rest);
        if (ns) locals.push(ns[1]);
        else if (/^[A-Za-z_$][\w$]*$/.test(rest)) locals.push(rest);
        else throw new Error(`armor-bundle: unparseable import binding in ${fileLabel}: ${stmt.slice(0, 80)}`);
      }
      if (named) for (const part of named.split(',')) {
        const name = part.trim().split(/\s+as\s+/).pop()?.trim();
        if (name) locals.push(name);
      }
    }
    imports.push({ stmt, specifier, locals });
  }
  return imports;
}

function extractExports(src) {
  const names = [];
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm)) names.push(m[1]);
  for (const m of src.matchAll(/^export\s*\{([\s\S]*?)\};?/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (name) names.push(name);
    }
  }
  return [...new Set(names)];
}

function stripExports(src) {
  return src
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\s)/gm, '')
    .replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, '');
}

function topLevelDecls(src) {
  const names = new Set();
  for (const m of src.matchAll(/^(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  for (const m of src.matchAll(/^const\s*\{([^}]*)\}/gm)) {
    for (const part of m[1].split(',')) { const n = part.trim().split(/[:=]/)[0]?.trim(); if (n) names.add(n); }
  }
  return names;
}

const stripImports = (src) => src.replace(IMPORT_RE, '')
  .replace(/^#!.*$/gm, ''); // a segment's shebang is only legal at byte 0 of its own file

// ── The merge ────────────────────────────────────────────────────────────────────────────────

/**
 * Merge the three runtime armor modules into ONE self-contained ES module:
 *   header  — the union of their node: builtin imports (deduped, binding-checked)
 *   scan    — body with exports stripped (armor.mjs's './scan.mjs' import is satisfied by scope)
 *   armor   — body with its scan import removed; everything else verbatim
 *   refit   — body inside an IIFE (its private helpers shadow armor's same-named internals),
 *             closing over armor's top-level names, its exports re-exported from the IIFE result
 * Throws on any shape the merge cannot prove safe: a non-builtin import, an export collision,
 * a top-level declaration collision, a default export, or scan.mjs's HERE line changing shape.
 */
export function mergeArmorSources({ armorSrc, scanSrc, refitSrc }) {
  for (const [label, src] of [['armor.mjs', armorSrc], ['scan.mjs', scanSrc], ['refit-net.mjs', refitSrc]]) {
    if (/^export\s+default/m.test(src)) throw new Error(`armor-bundle: ${label} has a default export — the merge does not carry one`);
  }
  const armorImports = parseImports(armorSrc, 'armor.mjs');
  const scanImports = parseImports(scanSrc, 'scan.mjs');
  const refitImports = parseImports(refitSrc, 'refit-net.mjs');
  for (const [label, list] of [['armor.mjs', armorImports], ['scan.mjs', scanImports], ['refit-net.mjs', refitImports]]) {
    for (const imp of list) {
      if (!imp.specifier.startsWith('node:') && imp.specifier !== './scan.mjs' && imp.specifier !== './armor.mjs') {
        throw new Error(`armor-bundle: ${label} imports ${imp.specifier} — only node: builtins and the armor-internal modules can merge`);
      }
    }
  }
  // Header: union of builtin import statements, deduped; one local name → one specifier, or stop.
  const bound = new Map();
  const header = [];
  for (const imp of [...scanImports, ...armorImports, ...refitImports]) {
    if (!imp.specifier.startsWith('node:')) continue;
    for (const local of imp.locals) {
      if (bound.has(local) && bound.get(local) !== imp.specifier) {
        throw new Error(`armor-bundle: import binding collision — ${local} is bound to both ${bound.get(local)} and ${imp.specifier}`);
      }
      bound.set(local, imp.specifier);
    }
    if (!header.includes(imp.stmt)) header.push(imp.stmt);
  }

  const armorExports = extractExports(armorSrc);
  const scanExports = extractExports(scanSrc);
  const refitExports = extractExports(refitSrc);
  const sets = [['armor', armorExports], ['scan', scanExports], ['refit', refitExports]];
  for (let i = 0; i < sets.length; i++) for (let j = i + 1; j < sets.length; j++) {
    const clash = sets[i][1].filter((n) => sets[j][1].includes(n));
    if (clash.length) throw new Error(`armor-bundle: export collision between ${sets[i][0]} and ${sets[j][0]}: ${clash.join(', ')}`);
  }

  // scan.mjs segment: its HERE constant derives from import.meta.url, which is a data: URL in
  // the evaluated bundle and would throw at module top level. HERE only feeds Ghidra/JDK tool
  // discovery (candidate paths), so a cwd fallback degrades exactly those lookups, nothing else.
  const HERE_LINE = 'const HERE = path.dirname(fileURLToPath(import.meta.url));';
  if (scanSrc.split(HERE_LINE).length !== 2) throw new Error('armor-bundle: scan.mjs HERE line not found exactly once — refusing to guess a rewrite');
  const scanBody = stripExports(stripImports(scanSrc)).replace(
    HERE_LINE,
    'const HERE = (() => { try { return path.dirname(fileURLToPath(import.meta.url)); } catch { return process.cwd(); } })();',
  );
  // scan.mjs's CLI-entry guard also calls fileURLToPath(import.meta.url) — under a truthy
  // process.argv[1] (every real boot) that throws for a data: module before the comparison can
  // say no. Rewrite it to a URL comparison that is false for data: and unchanged for files.
  const SCAN_GUARD = 'if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {';
  if (scanBody.split(SCAN_GUARD).length !== 2) throw new Error('armor-bundle: scan.mjs CLI guard not found exactly once — refusing to guess a rewrite');
  const scanBodyGuarded = scanBody.replace(
    SCAN_GUARD,
    'if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {',
  );

  const armorBody = stripExports(stripImports(armorSrc));
  const refitBody = stripExports(stripImports(refitSrc));

  const scanDecls = topLevelDecls(scanBodyGuarded);
  const armorDecls = topLevelDecls(armorBody);
  const declClash = [...scanDecls].filter((n) => armorDecls.has(n));
  if (declClash.length) throw new Error(`armor-bundle: top-level declaration collision scan/armor: ${declClash.join(', ')}`);
  for (const reserved of ['__refitNet']) {
    if (scanDecls.has(reserved) || armorDecls.has(reserved)) throw new Error(`armor-bundle: ${reserved} collides with the merge machinery`);
  }

  // The rewritten scan CLI guard (below) compares URLs via pathToFileURL, which none of the
  // three sources import — add it to the header unless a source already binds the name.
  if (bound.has('pathToFileURL') && bound.get('pathToFileURL') !== 'node:url') {
    throw new Error('armor-bundle: pathToFileURL is already bound to a different module');
  }
  if (!bound.has('pathToFileURL')) header.push("import { pathToFileURL } from 'node:url';");

  const refitWrapped = [
    'const __refitNet = (() => {',
    refitBody,
    `return { ${refitExports.join(', ')} };`,
    '})();',
    ...refitExports.map((n) => `export const ${n} = __refitNet.${n};`),
  ].join('\n');

  const code = [
    '// Scripture Armor — the runtime modules (armor.mjs + scan.mjs + refit-net.mjs) merged into one',
    '// module by the Kingmaker bake and sealed as armor-bundle.scripture. This text exists only',
    '// inside that sealed package and in memory at runtime; it is never a file in the payload.',
    ...header,
    '',
    scanBodyGuarded,
    '',
    armorBody,
    '',
    refitWrapped,
    '',
    `export { ${[...armorExports, ...scanExports].join(', ')} };`,
    '',
  ].join('\n');
  return { code, exports: { armor: armorExports, scan: scanExports, refit: refitExports } };
}

/** A loader shim standing at an original armor module path in the staged payload. */
export function armorShimSource(names) {
  return [
    SHIM_NOTE,
    "import { loadArmorModule } from '../lib/armor-bundle.mjs';",
    'const ns = await loadArmorModule();',
    ...names.map((n) => `export const ${n} = ns.${n};`),
    'export default ns;',
    '',
  ].join('\n');
}

/** The bake-generated pin module staged into lib/: signer pin + escrow identity for the loader. */
export function armorPinSource({ signerSignFp, escrowIdentityDoc }) {
  return [
    '// GENERATED BY THE KINGMAKER BAKE (lib/armor-bundle-build.mjs) — per-bake armor bundle pin.',
    '// BUNDLE_SIGNER_SIGN_FP pins the signer of armor-bundle.scripture + armor-bundle.key.scripture:',
    '// the loader refuses any package not signed by exactly this identity. ESCROW_IDENTITY is the',
    '// per-bake bootstrap identity the key escrow is sealed to; it opens nothing else, and once the',
    '// loader has provisioned the device-sealed copy (device identity, 0600 store) it is never used',
    '// again. Both values are minted fresh on every bake and rotate with the release.',
    `export const BUNDLE_SIGNER_SIGN_FP = ${JSON.stringify(signerSignFp)};`,
    `export const ESCROW_IDENTITY = ${JSON.stringify(escrowIdentityDoc)};`,
    '',
  ].join('\n');
}

// ── The staged transformation ────────────────────────────────────────────────────────────────

/**
 * Transform the staged payload's scripture-armor/ part in place (see the header). `stageRoot`
 * is the staged sol-ghost dir (its scripture-armor/ still holds the plaintext copies);
 * `armorModule` is the source tree's own scripture-armor/armor.mjs namespace, which does the
 * sealing. Returns { signerSignFp, bundleBytes, escrowBytes, exports }.
 */
export function sealArmorPart(stageRoot, { armorModule, log = () => {} } = {}) {
  const armorDir = join(stageRoot, 'scripture-armor');
  const sources = {
    armorSrc: readFileSync(join(armorDir, 'armor.mjs'), 'utf8'),
    scanSrc: readFileSync(join(armorDir, 'scan.mjs'), 'utf8'),
    refitSrc: readFileSync(join(armorDir, 'refit-net.mjs'), 'utf8'),
  };
  const merged = mergeArmorSources(sources);

  const scratch = mkdtempSync(join(tmpdir(), 'km-armor-bake-'));
  try {
    // Prove the merged module imports and carries the load-bearing exports BEFORE sealing it —
    // a bundle that cannot evaluate must never reach a payload.
    const probe = join(scratch, 'merged-probe.mjs');
    writeFileSync(probe, merged.code);
    const probeScript = 'const ns = await import(process.argv[1]);'
      + " for (const n of ['sealPlaintext','createIdentity','loadIdentity','parseScriptureFile','Flow','openFlow','scanSourceText','loadPolicy'])"
      + " { if (typeof ns[n] !== 'function') throw new Error('merged armor module is missing ' + n); }"
      + " console.log('merged armor module OK');";
    execFileSync(process.execPath, ['--input-type=module', '-e', probeScript, pathToFileURL(probe).href], { encoding: 'utf8' });

    const signer = armorModule.createIdentity(join(scratch, 'signer'), 'kingmaker-armor-bundle-signer');
    const bundleRecipient = armorModule.createIdentity(join(scratch, 'bundle'), 'kingmaker-armor-bundle');
    const escrow = armorModule.createIdentity(join(scratch, 'escrow'), 'kingmaker-armor-bundle-escrow');
    const peerOf = (id) => armorModule.parsePublicBlock(armorModule.publicBlock(id));

    const bundlePkg = armorModule.sealPlaintext(Buffer.from(merged.code, 'utf8'), signer, peerOf(bundleRecipient));
    const bundleRecipientDoc = readFileSync(join(scratch, 'bundle', 'identity.json'), 'utf8');
    const escrowPkg = armorModule.sealPlaintext(Buffer.from(bundleRecipientDoc, 'utf8'), signer, peerOf(escrow));
    const escrowDoc = JSON.parse(readFileSync(join(scratch, 'escrow', 'identity.json'), 'utf8'));

    writeFileSync(join(armorDir, BUNDLE_FILE), bundlePkg.text);
    writeFileSync(join(armorDir, ESCROW_FILE), escrowPkg.text);
    writeFileSync(join(armorDir, 'armor.mjs'), armorShimSource(merged.exports.armor));
    writeFileSync(join(armorDir, 'refit-net.mjs'), armorShimSource(merged.exports.refit));
    writeFileSync(join(armorDir, 'scan.mjs'), armorShimSource(merged.exports.scan));
    writeFileSync(join(stageRoot, 'lib', 'armor-bundle-pin.mjs'), armorPinSource({ signerSignFp: signer.signFp, escrowIdentityDoc: escrowDoc }));

    // Everything else of the armor tree leaves the payload: the daemon, cell, airlock, terms,
    // launcher, tests, harness (with its nested armor copies), docs and platform scripts are
    // the armor estate's own deployment, not Kingmaker payload content.
    for (const entry of readdirSync(armorDir, { withFileTypes: true })) {
      if (!ARMOR_BUNDLE_KEEP.includes(entry.name)) rmSync(join(armorDir, entry.name), { recursive: true, force: true });
    }
    log(`armor part sealed: bundle ${Buffer.byteLength(bundlePkg.text)} B, signer ${signer.signFp.slice(0, 16)}…`);
    return {
      signerSignFp: signer.signFp,
      bundleBytes: Buffer.byteLength(bundlePkg.text),
      escrowBytes: Buffer.byteLength(escrowPkg.text),
      exports: merged.exports,
    };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

export const armorBundleFilesPresent = (stageRoot) => ARMOR_BUNDLE_KEEP.every((f) => existsSync(join(stageRoot, 'scripture-armor', f)));

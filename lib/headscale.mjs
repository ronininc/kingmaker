/**
 * Activate the mesh on THIS (origin) installation. Provisions config + state on first run; completes
 * the CLI bootstrap (origin user + node #1 enrollment key) on the first run that finds a binary;
 * a byte-stable no-op after that. Returns { ok, changed, completedBootstrap, stubbed, record, dir }.
 * `exec`/`now`/`env`/`payloadRoot`/`spawnFn` are injected in tests; production callers pass only { stateDir }.
 */
export async function activateHeadscale({ stateDir, env = process.env, now = Date.now, exec = null, log = () => {}, payloadRoot = undefined, spawnFn = spawn } = {}) {
  if (!stateDir) throw new Error('activateHeadscale: a state dir is required');
  const p = headscalePaths(stateDir);
  const at = new Date(now()).toISOString();
  const ledger = (event) => { try { appendFileSync(p.ledger, `${JSON.stringify({ at: now(), ...event })}\n`); } catch { /* evidence, never a gate */ } };
  const existing = readJson(p.record);
  const binary = resolveHeadscaleBinary({ env, payloadRoot });
  const pin = loadHeadscalePin(payloadRoot);

  // A vendored binary runs only if its bytes still match the pin — the same drift doctrine as the
  // config: refused, never silently repaired, never run anyway. (An env-override binary is the
  // owner's own and is not pinned.)
  if (binary?.source === 'vendor' && binary.sha256) {
    let actual = null;
    try { actual = sha256Hex(readFileSync(binary.path)); } catch { /* unreadable counts as failed */ }
    if (actual !== binary.sha256) {
      return { ok: false, changed: false, reason: `vendored headscale binary fails its pin: ${binary.path} hashes ${actual ?? 'unreadable'}, pin.json records ${binary.sha256} — refusing to run it`, record: existing, dir: p.dir, stubbed: [] };
    }
  }

  if (existing) {
    // Drift is refused, never repaired: a config that no longer matches the record is a fact the
    // owner hears about, not a file activation quietly rewrites (and keys are never re-minted).
    let configNow = null;
    try { configNow = readFileSync(p.config, 'utf8'); } catch { /* missing counts as drift */ }
    if (!configNow || sha256Hex(configNow) !== existing.configSha256) {
      return { ok: false, changed: false, reason: 'headscale config drift: the config on disk does not match the activation record — refusing to rewrite or re-mint', record: existing, dir: p.dir, stubbed: [] };
    }
    if (existing.bootstrap === 'complete') {
      return { ok: true, changed: false, completedBootstrap: false, stubbed: [], record: existing, dir: p.dir };
    }
    if (!binary) {
      return { ok: true, changed: false, completedBootstrap: false, stubbed: [HEADSCALE_ACQUISITION_STUB.name, 'cli-bootstrap'], record: existing, dir: p.dir };
    }
    // Provisioned earlier without a binary; the config stays exactly as written — only the bootstrap
    // (and the record that reports it) moves.
    const record = await bootstrap({ p, stateDir, binary, exec, env, now, at, existing, spawnFn, pin });
    log('bootstrapped', { node: ORIGIN_NODE });
    return { ok: true, changed: true, completedBootstrap: true, stubbed: [], record, dir: p.dir };
  }

  // First activation on this installation: provision the state tree.
  mkdirSync(p.dir, { recursive: true, mode: 0o700 });
  const port = Number(env.KINGMAKER_HEADSCALE_PORT || DEFAULT_HEADSCALE_PORT) || DEFAULT_HEADSCALE_PORT;
  const config = buildHeadscaleConfig({ stateDir, port, serverUrl: String(env.KINGMAKER_HEADSCALE_SERVER_URL ?? '').trim() || null });
  writeAtomic(p.config, config);
  if (!existsSync(p.keys)) writeFileSync(p.keys, `${JSON.stringify({ minted: [], revoked: [] }, null, 2)}\n`, { mode: 0o600 });
  ledger({ type: 'provisioned' });
  log('provisioned', { dir: p.dir });

  const base = {
    schema: HEADSCALE_SCHEMA,
    activatedAt: at,
    origin: { node: ORIGIN_NODE, user: ORIGIN_USER, keyJti: null, keyExp: null },
    configSha256: sha256Hex(config),
    binary: binaryRecord(binary),
    binaryPin: pinSummary(pin),
    pendingPlatform: binary ? null : headscalePlatformKey(),
    vendoredPlatforms: pin ? Object.keys(pin.platforms) : [],
    bootstrap: 'pending-binary',
  };
  if (!binary) {
    writeAtomic(p.record, `${JSON.stringify(base, null, 2)}\n`);
    return { ok: true, changed: true, completedBootstrap: false, stubbed: [HEADSCALE_ACQUISITION_STUB.name, 'cli-bootstrap'], record: base, dir: p.dir };
  }
  const record = await bootstrap({ p, stateDir, binary, exec, env, now, at, existing: base, spawnFn, pin });
  log('bootstrapped', { node: ORIGIN_NODE });
  return { ok: true, changed: true, completedBootstrap: true, stubbed: [], record, dir: p.dir };
}

/** The CLI bootstrap: the origin user, then node #1's enrollment key, minted under the installation's
 *  authority and recorded in the activation record. Runs once; the record is its receipt. The pinned
 *  CLI administers a running server, so the bootstrap serves briefly itself — start, wait for the
 *  listening line, run the CLI, stop — and the supervised serve starts separately afterwards. */
async function bootstrap({ p, stateDir, binary, exec, env, now, at, existing, spawnFn = spawn, pin = null }) {
  const cli = createHeadscaleCli({ binary: binary.path, configPath: p.config, exec, env });
  const proc = startHeadscaleProcess({ binary: binary.path, stateDir, spawnFn, env });
  try {
    await proc.ready;
    await cli.createUser(ORIGIN_USER);
    const store = openMeshKeyStore(p.dir, { now });
    const { claims } = await store.mint({ cli, label: 'origin — node #1', minutes: DEFAULT_ENROLL_MINUTES, mintedBy: 'kingmaker' });
    const record = {
      ...existing,
      activatedAt: existing.activatedAt ?? at,
      origin: { node: ORIGIN_NODE, user: ORIGIN_USER, keyJti: claims.jti, keyExp: claims.exp },
      binary: binaryRecord(binary),
      binaryPin: pinSummary(pin),
      pendingPlatform: null,
      bootstrap: 'complete',
      bootstrappedAt: at,
    };
    writeAtomic(p.record, `${JSON.stringify(record, null, 2)}\n`);
    try { appendFileSync(p.ledger, `${JSON.stringify({ at: now(), type: 'bootstrapped', node: ORIGIN_NODE, keyJti: claims.jti })}\n`); } catch { /* evidence, never a gate */ }
    return record;
  } finally {
    await proc.stop().catch(() => {});
  }
}

// ── Supervision: the tree's pattern, the tree's numbers (lib/runtime.mjs superviseBackend) ──

const READY_LINE = /listening/i;

/**
 * One control-plane process as a backend handle in superviseBackend's shape ({ child, ready, exited,
 * stop }) — the same shape lib/runtime.mjs startBackend returns for the core. `ready` settles when the
 * process prints its listening line; output is kept in the mesh folder's own log.
 */
export function startHeadscaleProcess({ binary, stateDir, spawnFn = spawn, stopGraceMs = 5_000, env = process.env } = {}) {
  if (!binary) throw new Error('startHeadscaleProcess: a binary is required (none resolved for this platform — see HEADSCALE_ACQUISITION_STUB)');
  const p = headscalePaths(stateDir);
  mkdirSync(p.dir, { recursive: true, mode: 0o700 });
  const sink = createWriteStream(p.log, { flags: 'a' });
  const child = spawnFn(binary, ['--config', p.config, 'serve'], { cwd: p.dir, env, stdio: ['ignore', 'pipe', 'pipe'] });
  let readyResolve; let readyReject;
  const ready = new Promise((resolve, reject) => { readyResolve = resolve; readyReject = reject; });
  ready.catch(() => {});
  let tail = '';
  const onData = (chunk) => {
    sink.write(chunk);
    tail = (tail + chunk.toString('utf8')).slice(-4096);
    if (READY_LINE.test(tail)) readyResolve();
  };
  child.stdout?.on('data', onData);
  child.stderr?.on('data', onData);
  const exited = new Promise((resolve) => child.once('exit', (code, signal) => {
    readyReject(new Error(`headscale exited before its listening line (code ${code}, signal ${signal}) — see ${p.log}`));
    sink.end();
    resolve({ code, signal });
  }));
  const stop = async () => {
    if (child.exitCode !== null || child.signalCode !== null) return exited;
    child.kill('SIGTERM');
    const force = setTimeout(() => { try { child.kill('SIGKILL'); } catch { /* gone */ } }, stopGraceMs);
    force.unref?.();
    const result = await exited;
    clearTimeout(force);
    return result;
  };
  return { child, ready, exited, stop, logPath: p.log };
}

/** Supervise the control plane exactly as the core is supervised: bounded restart (1 s, 3 s, 9 s; at
 *  most 3 within a minute; a healthy 5 minutes earns a fresh budget), never after an intentional stop.
 *  Events (onEvent): restarting / restarted / recovered / gave_up, as superviseBackend emits them. */
export function superviseHeadscale(first, { binary, stateDir, spawnFn = spawn, onEvent = () => {}, now = Date.now, schedule, cancel, env = process.env } = {}) {
  return superviseBackend(first, {
    relaunch: async () => startHeadscaleProcess({ binary, stateDir, spawnFn, env }),
    onEvent,
    now,
    ...(schedule ? { schedule } : {}),
    ...(cancel ? { cancel } : {}),
    // No second rules layer rides on the control plane: its rules are its config, checked at activation.
    verify: async () => true,
  });
}

/**
 * Activation + supervision in one act — what `kingmaker start` calls. Fail-soft by design: any problem
 * (no binary yet, a CLI refusal, a config drift) is reported in the result and logged, and null is
 * returned; the mesh never takes the core down with it. On success returns { record, supervisor, stop }.
 */
export async function activateAndSuperviseMesh({ stateDir, env = process.env, now = Date.now, exec = null, spawnFn = spawn, log = () => {}, payloadRoot = undefined } = {}) {
  const mlog = (event, detail) => { try { log(`mesh_${event}`, detail); } catch { /* reporting never breaks the mesh */ } };
  try {
    const r = await activateHeadscale({ stateDir, env, now, exec, log: mlog, payloadRoot, spawnFn });
    if (!r.ok) { mlog('refused', { reason: r.reason ?? 'unknown' }); return null; }
    if (r.record?.bootstrap !== 'complete') { mlog('pending', { stubbed: r.stubbed }); return null; }
    const binary = resolveHeadscaleBinary({ env, payloadRoot });
    if (!binary) { mlog('pending', { stubbed: [HEADSCALE_ACQUISITION_STUB.name] }); return null; }
    const first = startHeadscaleProcess({ binary: binary.path, stateDir, spawnFn, env });
    const supervisor = superviseHeadscale(first, {
      binary: binary.path, stateDir, spawnFn, env,
      onEvent: (name, detail) => { const { backend, ...rest } = detail ?? {}; mlog(name, { ...rest, ...(backend ? { pid: backend.child?.pid ?? null } : {}) }); },
    });
    mlog('started', { pid: first.child?.pid ?? null, node: ORIGIN_NODE });
    return { record: r.record, supervisor, stop: () => supervisor.stop() };
  } catch (error) {
    mlog('failed', { message: String(error?.message ?? error).slice(0, 200) });
    return null;
  }
}

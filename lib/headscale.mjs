/** The platform key the pin record is indexed by: '<platform>-<arch>' in the upstream (Go) naming
 *  the pin is generated from — Node calls the same arch 'x64', Go calls it 'amd64'; the alias keeps
 *  the pin's vocabulary the single one. (darwin-arm64, linux-amd64, …) */
const HEADSCALE_ARCH_ALIASES = Object.freeze({ x64: 'amd64' });
export const headscalePlatformKey = (platform = process.platform, arch = process.arch) => `${platform}-${HEADSCALE_ARCH_ALIASES[arch] ?? arch}`;

export const headscaleVendorDir = (payloadRoot) => join(payloadRoot, 'vendor', 'headscale');

/** The pin record beside the vendored binaries, or null when this payload carries none. The pin is
 *  data, generated by scripts/vendor-headscale.mjs from the upstream checksums — this module reads
 *  it, never invents it. */
export function loadHeadscalePin(payloadRoot = fileURLToPath(new URL('..', import.meta.url))) {
  const pin = readJson(join(headscaleVendorDir(payloadRoot), PIN_FILE));
  if (!pin || pin.schema !== HEADSCALE_PIN_SCHEMA || !pin.platforms) return null;
  return pin;
}

/** Where the headscale binary is: the env override first, then the payload's vendored asset for THIS
 *  platform (per the pin), then the legacy single-file vendor slot. A resolved vendored binary
 *  carries its pin entry (version, platform, sha256) with it. Null when absent for this platform —
 *  the acquisition seam's pending state, reported as such, never papered over. */
export function resolveHeadscaleBinary({ env = process.env, payloadRoot = fileURLToPath(new URL('..', import.meta.url)), exists = existsSync, platform = process.platform, arch = process.arch } = {}) {
  const fromEnv = String(env.KINGMAKER_HEADSCALE_BIN ?? '').trim();
  if (fromEnv) return exists(fromEnv) ? { path: fromEnv, source: 'env', platform: null, version: null, sha256: null } : null;
  const key = headscalePlatformKey(platform, arch);
  const pin = loadHeadscalePin(payloadRoot);
  const entry = pin?.platforms?.[key];
  const vendored = join(headscaleVendorDir(payloadRoot), entry?.file ?? `headscale-${key}`);
  if (exists(vendored)) {
    return { path: vendored, source: 'vendor', platform: key, version: pin?.version ?? null, sha256: entry?.sha256 ?? null };
  }
  const legacy = join(headscaleVendorDir(payloadRoot), 'headscale');
  if (legacy !== vendored && exists(legacy)) {
    return { path: legacy, source: 'vendor', platform: null, version: pin?.version ?? null, sha256: null };
  }
  return null;
}

/** The acquisition seam itself: landed for the platforms the pin carries (reports the resolved binary
 *  + its pin entry); for any other platform it reports that platform PENDING — named, with the
 *  vendored platforms listed — and activation records bootstrap: 'pending-binary' for exactly it. */
export function acquireHeadscaleBinary(opts = {}) {
  const found = resolveHeadscaleBinary(opts);
  if (found) return { ok: true, ...found, stub: false };
  const payloadRoot = opts.payloadRoot ?? fileURLToPath(new URL('..', import.meta.url));
  const pin = loadHeadscalePin(payloadRoot);
  return {
    ok: false,
    stub: true,
    seam: HEADSCALE_ACQUISITION_STUB.name,
    wanted: HEADSCALE_ACQUISITION_STUB.wanted,
    platform: headscalePlatformKey(opts.platform, opts.arch),
    vendoredPlatforms: pin ? Object.keys(pin.platforms) : [],
    version: pin?.version ?? null,
  };
}

// ── The CLI surface ──────────────────────────────────────────────────────────
// Everything this module asks of headscale goes through these argv shapes (the PINNED release's —
// verified against the vendored 0.29.6 binary, not assumed):
//   [--config C] users create <name>                       (a duplicate fails on the name constraint)
//   [--config C] users list -o json                        ([{ id, name, … }] — the name → ID lookup)
//   [--config C] preauthkeys create --user <numeric ID> --expiration <dur> [--reusable]
//   [--config C] serve            (the control plane itself)
// The pinned CLI talks to a RUNNING server over the config's unix socket — there is no offline
// mode — so the bootstrap (below) starts a throwaway serve, runs these, and stops it again.
// `run(argv) → { code, stdout, stderr }` is injected in tests with a fake binary behind it.

const defaultExec = (binary, argv, env) => new Promise((resolve) => {
  execFile(binary, argv, { timeout: 30_000, env }, (error, stdout, stderr) => {
    resolve({ code: error ? (error.code ?? 1) : 0, stdout: String(stdout ?? ''), stderr: String(stderr ?? (error?.message ?? '')) });
  });
});

export function createHeadscaleCli({ binary, configPath, exec = null, env = process.env } = {}) {
  if (!binary) throw new Error('createHeadscaleCli: a binary is required');
  const run = (argv) => (exec ?? ((a) => defaultExec(binary, a, env)))(['--config', configPath, ...argv]);
  const fail = (what, r) => new Error(`headscale ${what} failed (exit ${r.code}): ${String(r.stderr || r.stdout).trim().slice(0, 200)}`);
  return Object.freeze({
    binary,
    /** Create a user. One who already exists is not an error — activation is idempotent end to end.
     *  The pinned release reports a duplicate as a name-constraint failure, not "already exists";
     *  both wordings mean the user stands. */
    async createUser(name) {
      const r = await run(['users', 'create', name]);
      if (r.code === 0) return { created: true };
      if (/already exists/i.test(`${r.stderr} ${r.stdout}`) || /unique constraint failed:\s*users\.name/i.test(`${r.stderr} ${r.stdout}`)) return { created: false, existed: true };
      throw fail(`users create ${name}`, r);
    },
    /** The numeric ID the pinned CLI addresses users by, resolved from the user list. Throws when
     *  the user is not there — a key is never minted against a guessed ID. */
    async userId(name) {
      const r = await run(['users', 'list', '-o', 'json']);
      if (r.code !== 0) throw fail('users list', r);
      let users;
      try { users = JSON.parse(r.stdout); } catch { throw new Error('headscale users list printed no JSON user list'); }
      const found = Array.isArray(users) ? users.find((u) => u && (u.name === name || u.username === name)) : null;
      if (!found || !Number.isFinite(Number(found.id))) throw new Error(`headscale user ${name} not found in the user list`);
      return Number(found.id);
    },
    /** Mint a preauth (enrollment) key for `user` (a NAME here; the adapter resolves the pinned
     *  CLI's numeric ID itself). Headscale prints the key; it is returned once and
     *  never stored by this module — the store keeps only its sha256 (openMeshKeyStore). */
    async createPreauthKey({ user, minutes, reusable = false } = {}) {
      const id = await this.userId(user);
      const argv = ['preauthkeys', 'create', '--user', String(id), '--expiration', `${Math.max(1, Math.round(minutes))}m`];
      if (reusable) argv.push('--reusable');
      const r = await run(argv);
      if (r.code !== 0) throw fail('preauthkeys create', r);
      const lines = String(r.stdout).split('\n').map((s) => s.trim()).filter(Boolean);
      const key = lines.find((l) => l.startsWith('hskey-auth-')) ?? lines[lines.length - 1];
      if (!key) throw new Error('headscale preauthkeys create printed no key');
      return key;
    },
  });
}

// ── Enrollment keys: the tree's token patterns (lib/k-office.mjs), cut for the mesh ──
// Only the activation authority mints ('kingmaker'); the capability set is exactly ENROLL_CAPS and asking
// for anything else throws; durations clamp to MAX_ENROLL_MINUTES; records carry scope + iat + exp and a
// live state (active / expired / revoked), and verification fails closed. Revocation is a record act:
// Kingmaker never hands the key out again and never honors it on its own surfaces; the key itself dies
// at its recorded expiry — enrollment keys are short-lived (24 h default, 7 d maximum) precisely so the
// record is enough. The headscale-side state lives in headscale's own db, which this module never opens.

export function openMeshKeyStore(dir, { now = Date.now } = {}) {
  const file = join(dir, KEYS_FILE);
  const ledgerFile = join(dir, LEDGER_FILE);
  const ensureDir = () => mkdirSync(dir, { recursive: true, mode: 0o700 });
  const read = () => {
    try { const t = JSON.parse(readFileSync(file, 'utf8')); return { minted: t.minted ?? [], revoked: t.revoked ?? [] }; }
    catch { return { minted: [], revoked: [] }; }
  };
  const write = (t) => { ensureDir(); writeFileSync(file, `${JSON.stringify(t, null, 2)}\n`, { mode: 0o600 }); };
  const ledger = (event) => { try { ensureDir(); appendFileSync(ledgerFile, `${JSON.stringify({ at: now(), ...event })}\n`); } catch { /* the ledger is evidence, never a gate */ } };
  const stateOf = (m, t) => (t.revoked.includes(m.jti) ? 'revoked' : now() > m.exp ? 'expired' : 'active');

  return Object.freeze({
    dir,
    now,
    /**
     * Mint a family-device enrollment key through the control plane's own CLI. Kingmaker only. The
     * returned key string is handed to the device once; the store keeps its claims and its sha256.
     */
    async mint({ cli, label, minutes = DEFAULT_ENROLL_MINUTES, capabilities = null, mintedBy } = {}) {
      if (mintedBy !== 'kingmaker') throw new Error('only Kingmaker mints enrollment keys');
      if (!cli) throw new Error('minting an enrollment key needs the control plane CLI (no binary, no keys)');
      const caps = [...new Set((capabilities ?? ENROLL_CAPS).map(String))];
      for (const c of caps) {
        if (c.endsWith(':execute')) throw new Error(`capability refused: ${c} — an enrollment key never executes anything`);
        if (!ENROLL_CAPS.includes(c)) throw new Error(`capability ${c} is outside the enrollment scope (${ENROLL_CAPS.join(', ')})`);
      }
      if (!caps.length) throw new Error('an enrollment key needs its join capability');
      const mins = Math.min(Math.max(1, Math.floor(minutes)), MAX_ENROLL_MINUTES);
      const iat = now();
      const key = await cli.createPreauthKey({ user: ORIGIN_USER, minutes: mins });
      const claims = {
        jti: randomBytes(9).toString('base64url'),
        label: String(label ?? 'family device').slice(0, 60),
        caps, iat, exp: iat + mins * MINUTE, mintedBy,
        keySha256: sha256Hex(key),
      };
      const t = read();
      t.minted.push(claims);
      write(t);
      ledger({ type: 'mint', jti: claims.jti, label: claims.label, caps, exp: claims.exp });
      return { key, claims };
    },
    /** Fail-closed, like the office: unknown, revoked or expired verifies as exactly nothing. */
    verifyRecord(jti, { capability = null } = {}) {
      const t = read();
      const m = t.minted.find((x) => x.jti === jti);
      if (!m) return { ok: false, reason: 'enrollment key not minted by this installation' };
      if (t.revoked.includes(m.jti)) return { ok: false, reason: 'enrollment key revoked' };
      if (now() > m.exp) return { ok: false, reason: 'enrollment key expired' };
      if (capability && !m.caps.includes(capability)) return { ok: false, reason: `capability ${capability} not in scope` };
      return { ok: true, claims: m };
    },
    /** Revoke by jti (record act — see the header of this section). True when a live key was revoked. */
    revoke(jti) {
      const t = read();
      const m = t.minted.find((x) => x.jti === jti);
      if (!m || t.revoked.includes(jti)) return false;
      t.revoked.push(jti);
      write(t);
      ledger({ type: 'revoke', jti });
      return true;
    },
    /** Minted-key metadata (never key strings), each with its live state. */
    listKeys() {
      const t = read();
      return t.minted.map((m) => ({ ...m, state: stateOf(m, t) }));
    },
  });
}


const readJson = (f) => { try { return JSON.parse(readFileSync(f, 'utf8')); } catch { return null; } };
const writeAtomic = (f, text) => {
  const tmp = `${f}.${process.pid}.tmp`;
  writeFileSync(tmp, text, { mode: 0o600 });
  renameSync(tmp, f);
};

/** The activation record as it stands, or null when this installation has no mesh yet. */
export const readMeshRecord = (stateDir) => (stateDir ? readJson(headscalePaths(stateDir).record) : null);

/** Read-only status for surfaces (the `kingmaker mesh` verb): the record + key metadata, nothing sealed. */
export function meshStatus(stateDir, { now = Date.now } = {}) {
  const record = readMeshRecord(stateDir);
  if (!record) return { schema: HEADSCALE_SCHEMA, active: false, record: null, keys: [] };
  const store = openMeshKeyStore(headscaleDir(stateDir), { now });
  return { schema: HEADSCALE_SCHEMA, active: true, record, keys: store.listKeys() };
}


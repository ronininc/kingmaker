#!/bin/sh
# Bundle Solomon's fleet-learning packet, sanitizer and vocabulary (TSS server/src/runtime/fleet-learning) into one plain
# ES module for Kingmaker's engine glue (vendor/fleet/fleet-packet.mjs), so the packet a Mac builds and validates is the
# exact one Solomon defines. Re-run after the packet changes in TSS:  scripts/build-fleet-vendor.sh [path/to/TSS]
set -eu
here="$(cd "$(dirname "$0")/.." && pwd -P)"
tss="${1:-${TSS_DIR:-$HOME/Projects/TSS}}"
src="$tss/server/src/runtime/fleet-learning"
[ -f "$src/sanitizer.ts" ] || { echo "no fleet-learning sources at $src" >&2; exit 1; }
entry="$(mktemp -d)/entry.ts"
cat > "$entry" <<TS
export { sanitizeForFleet, preferenceKind, newInstallationId, MIN_WORD_SUPPORT, MIN_ROUTE_EXAMPLES } from '$src/sanitizer.ts';
export { validatePacket, canonicalJson, FLEET_PACKET_SCHEMA_ID, PREFERENCE_KINDS, PREFERENCE_POLARITIES } from '$src/packet.ts';
TS
"$tss/node_modules/.bin/esbuild" "$entry" --bundle --platform=node --format=esm --target=node20 --legal-comments=none \
  --banner:js="// GENERATED by scripts/build-fleet-vendor.sh from the engine's fleet-learning source. Do not edit." \
  --outfile="$here/vendor/fleet/fleet-packet.mjs"
# The public tree never names the engine's source checkout: esbuild's path comments keep only the fleet-learning part.
sed -i '' 's#^// .*/fleet-learning/#// fleet-learning/#' "$here/vendor/fleet/fleet-packet.mjs"
echo "built vendor/fleet/fleet-packet.mjs from $(git -C "$tss" rev-parse --abbrev-ref HEAD)@$(git -C "$tss" rev-parse --short HEAD)"

#!/usr/bin/env node
// Render docs/MAC-BENCH.md from every catalog/bench/*.json that `kingmaker models bench` wrote, so the results table
// in the repo is the measurements themselves and can't drift from them. Run: node scripts/bench-table.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { BENCH_SETS, CHIP_BANDWIDTH, CLASSES, PACKS, PROFILES, ROLES, classFor } from '../lib/mac-profiles.mjs';
import { verdict } from '../lib/model-bench.mjs';

const dir = new URL('../catalog/bench/', import.meta.url);
const files = readdirSync(dir).filter((f) => /^m\d.*\.json$/.test(f)).sort();
const meta = Object.fromEntries(Object.values(BENCH_SETS).flat().map((m) => [m.tag, m]));
const short = (t) => t.replace(/^huihui_ai\//, '').replace(/^hf\.co\//, 'hf: ').replace(/-GGUF:/i, ':');
const n = (v, d = 1) => (v == null || Number.isNaN(v) ? '—' : Number(v).toFixed(d));
const kinds = (t) => (t?.by ? ['single', 'multi', 'chain', 'refuse'].map((k) => `${t.by[k]?.pass ?? 0}/${t.by[k]?.of ?? 0}`).join(' · ') : '—');

let md = `# Kingmaker model benchmarks, per Mac

Generated by \`node scripts/bench-table.mjs\` from \`catalog/bench/*.json\` (written by \`kingmaker models bench\`). Do not edit
by hand: re-run the bench, then this script. How the bench works and what each column means: [MAC-PROFILES.md](MAC-PROFILES.md).

- **Holds**: the model runner's RSS after every suite ran (weights, a used context, compute buffers). **Peak** adds the
  moment of loading. **Fits** compares Holds with the profile's per-model budget, and also requires the whole model on the
  GPU and no swap growth.
- **Tools**: 18 cases through Kingmaker's two-step structured calls (pick, then arguments, each held to a JSON schema),
  and through Ollama's native \`tools\`. Kinds: single · multi-argument · two chained tools · refusing when no tool fits.
- **Route**: 12 commands the rules can't place, answered under the router's lane schema. **Write**: 3 tasks with
  checkable limits (exactly two sentences, exactly three bullets, under 30 words).
`;

for (const f of files) {
  const b = JSON.parse(readFileSync(new URL(f, dir), 'utf8'));
  const cls = b.simulated ? classFor(b.simulated.asGb) : classFor(b.host.ramGb);
  const budget = PROFILES[cls].maxResidentGb;   // judged against the current budget, not the one at bench time
  md += `\n## ${b.host.chip}, ${b.host.ramGb} GB${b.simulated ? ` simulated as an ${b.simulated.asGb} GB Mac` : ''} (\`${f}\`)\n\n`;
  md += `macOS ${b.host.macos}, Ollama ${b.host.ollama}, ${b.host.model}. Context ${b.context} tokens. Budget ${budget} GB per model (the ${cls} GB profile). Measured ${String(b.startedAt).slice(0, 10)}.\n`;
  if (b.simulated) md += `\n> ${b.simulated.honest} Ollama's scheduler saw: ${b.simulated.schedulerSaw ? `available ${b.simulated.schedulerSaw.available} on the GPU` : 'n/a'} (a real 8 GB M3's Ollama log shows available 4.8 GiB).\n`;
  md += '\n| Model | Role | Load s | tok/s | Holds GB | Peak GB | Tools (2-step) | Kinds (2-step) | Tools (native) | Route | Write | Fits |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n';
  const rows = b.results.map((r) => ({ r, v: verdict(r, { maxResidentGb: budget }), m: meta[r.model] ?? meta[`${r.model}:latest`] ?? {} }));
  const order = ['router', 'writer', 'coder', 'vision', 'reasoning'];
  rows.sort((a, c) => (order.indexOf(a.m.role) - order.indexOf(c.m.role)) || ((c.v.tools ?? -1) - (a.v.tools ?? -1)));
  for (const { r, v, m } of rows) {
    if (r.error) { md += `| ${short(r.model)} | ${m.role ?? '—'} | ✗ ${r.error.replace(/\|/g, '/')} |||||||||| ✗ |\n`; continue; }
    md += `| ${short(r.model)} | ${m.role ?? '—'} | ${n(r.loadS, 2)} | ${n(r.speed?.genTokS)} | ${n(r.memory?.steadyRssGb, 2)} | ${n(r.memory?.peakRssGb, 2)} | ${v.tools ?? '—'}% | ${kinds(r.tools?.twoStep)} | ${v.nativeTools ?? '—'}% | ${v.route ?? '—'}% | ${v.write ?? '—'}% | ${v.fits ? '✓' : `✗ ${v.why}`} |\n`;
  }
}

const out = new URL('../docs/MAC-BENCH.md', import.meta.url);
writeFileSync(out, md);
console.log(`✓ ${files.length} bench file(s) → ${out.pathname}`);

// The profile table in docs/MAC-PROFILES.md, between its markers, from lib/mac-profiles.mjs itself.
const ref = (() => { try { return JSON.parse(readFileSync(new URL('m5-pro-24gb.json', dir), 'utf8')).results; } catch { return []; } })();
const sim = (() => { try { return JSON.parse(readFileSync(new URL('m5-pro-24gb-as-8gb.json', dir), 'utf8')).results; } catch { return []; } })();
const speed = (cls, tag) => (cls === 8 ? sim : ref).find((r) => r.model === tag)?.speed?.genTokS;
let t = '| Pack | Macs | Router | Writer | Coder | Vision | Reasoning | Per model | Context | At once | Voice | Pictures | Download | Basis |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n';
for (const c of CLASSES) {
  const p = PROFILES[c], pk = PACKS.find((x) => x.id === String(c));
  t += `| **${pk.name}** | ${p.label} | ${ROLES.map((r) => `\`${short(p[r])}\``).join(' | ')} | ${p.maxResidentGb} GB | ${p.context / 1024}k | ${p.concurrent} | ${p.voice === 'on' ? 'on' : 'text only'} | ${p.imageLane ? 'on' : 'off'} | ${pk.downloadGb} GB | ${/^estimate/.test(p.basis) ? 'estimate' : 'measured'} |\n`;
}
t += '\nExpected writer speed by chip (decode is bound by memory bandwidth, so this scales the measured tok/s by each chip\'s bandwidth; an **estimate**, except the M5 Pro row, which is measured). It runs optimistic on a small, busy Mac: on 2026-10-09 the real 8 GB M3 ran the Qwen3 1.7B at 23–28 tok/s, where this scaling predicts ~59 (the M5 Pro measures 181), so expect up to half these numbers on an 8 GB Mac until its own bench says otherwise:\n\n| Chip | GB/s | 8 GB writer (Granite 3B) | 16–24 GB writer (Qwen3 8B) |\n|---|---|---|---|\n';
const g = speed(8, PROFILES[8].writer), q = speed(24, PROFILES[24].writer), refBw = CHIP_BANDWIDTH['M5 Pro'];
for (const [chip, bw] of Object.entries(CHIP_BANDWIDTH)) t += `| ${chip} | ${bw} | ${g ? `~${Math.round(g * bw / refBw)} tok/s` : '—'} | ${q ? `~${Math.round(q * bw / refBw)} tok/s` : '—'}${chip === 'M5 Pro' ? ' (measured)' : ''} |\n`;
const prof = new URL('../docs/MAC-PROFILES.md', import.meta.url);
try {
  const doc = readFileSync(prof, 'utf8');
  const next = doc.replace(/<!-- profiles:start -->[\s\S]*<!-- profiles:end -->/, `<!-- profiles:start -->\n${t}<!-- profiles:end -->`);
  writeFileSync(prof, next); console.log(`✓ profile table → ${prof.pathname}`);
} catch { /* no MAC-PROFILES.md yet */ }
